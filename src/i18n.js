export function getInitialLanguage() {
  try {
    const stored = globalThis.localStorage?.getItem(LANGUAGE_STORAGE_KEY);
    return SUPPORTED_LANGUAGES.includes(stored) ? stored : "el";
  } catch {
    return "el";
  }
}

export function saveLanguage(language) {
  try {
    globalThis.localStorage?.setItem(
      LANGUAGE_STORAGE_KEY,
      SUPPORTED_LANGUAGES.includes(language) ? language : "el",
    );
  } catch {
    // Language switching still works when strict browser storage rejects writes.
  }
}

export function localeForLanguage(language) {
  return language === "en" ? "en-GB" : "el-GR";
}

export function translationKeys(language) {
  return Object.keys(messages[language] || {}).sort();
}

export function translate(language, key, values = {}) {
  const selectedMessages = messages[language] || messages.el;
  const message = selectedMessages[key] ?? messages.el[key] ?? key;
  return typeof message === "function" ? message(values) : message;
}
